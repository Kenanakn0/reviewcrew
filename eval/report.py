"""Render evaluation results as Markdown."""

from collections.abc import Sequence
from statistics import mean

from pydantic import BaseModel, ConfigDict

from eval.scoring import AGENTS, Counts, total
from reviewcrew.agents.models import AgentName
from reviewcrew.llm.base import TokenUsage

README_START = "<!-- eval-results:start -->"
README_END = "<!-- eval-results:end -->"


class CaseResult(BaseModel):
    model_config = ConfigDict(frozen=True)

    name: str
    clean: bool
    counts: dict[AgentName, Counts]  # LLM agents only
    rule_counts: Counts = Counts()  # the deterministic secret scan, scored as security
    usage: TokenUsage
    cost_usd: float | None
    duration_seconds: float
    errors: tuple[str, ...] = ()


class RunInfo(BaseModel):
    model_config = ConfigDict(frozen=True)

    model: str
    settings: str  # e.g. "effort high, min confidence 0.5"
    date: str


def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value:.0%}"


def _row(label: str, counts: Counts) -> str:
    return (
        f"| {label} | {counts.tp + counts.fn} | {counts.tp + counts.fp} | {counts.tp} | "
        f"{counts.fp} | {counts.fn} | {_pct(counts.precision)} | {_pct(counts.recall)} | "
        f"{_pct(counts.f1)} |"
    )


def _rule_row(counts: Counts) -> str:
    # The scan targets one kind of security issue, so recall over all security cases is
    # not meaningful; precision is.
    return (
        f"| secret scan (rule) | — | {counts.tp + counts.fp} | {counts.tp} | {counts.fp} | — | "
        f"{_pct(counts.precision)} | — | — |"
    )


def summary_table(results: Sequence[CaseResult], info: RunInfo) -> str:
    """The headline numbers (also embedded in the README)."""
    per_agent = total(r.counts for r in results)
    overall = sum(per_agent.values(), Counts())
    rules = sum((r.rule_counts for r in results), Counts())
    clean = [r for r in results if r.clean]
    clean_fp = sum(sum(c.fp for c in r.counts.values()) for r in clean)
    clean_rule_fp = sum(r.rule_counts.fp for r in clean)
    costs = [r.cost_usd for r in results if r.cost_usd is not None]
    lines = [
        f"Model `{info.model}` ({info.settings}) · {len(results)} cases, {len(clean)} of "
        f"them clean · {info.date}",
        "",
        "| Agent | Expected | Reported | TP | FP | FN | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        *(_row(agent, per_agent[agent]) for agent in AGENTS),
        _row("**all LLM agents**", overall),
        _rule_row(rules),
        "",
        "| Per case | Mean |",
        "|---|---:|",
        f"| Tokens | {mean(r.usage.total_tokens for r in results):,.0f} |",
        f"| Cost (list price) | "
        f"{'$' + format(mean(costs), '.4f') if costs else 'n/a (local or unpriced model)'} |",
        f"| Duration (agents in parallel) | {mean(r.duration_seconds for r in results):.1f}s |",
        "",
        f"False positives on the {len(clean)} clean cases: {clean_fp} from the LLM agents, "
        f"{clean_rule_fp} from the secret scan.",
    ]
    return "\n".join(lines)


def full_report(results: Sequence[CaseResult], info: RunInfo) -> str:
    lines = [
        "# ReviewCrew evaluation results",
        "",
        "Generated by `uv run python -m eval.run`. A prediction is a true positive when it has",
        "the expected category and file and lies within 2 lines of the expected range; each",
        "expected finding can be matched once. Findings are counted after aggregation (the",
        "confidence threshold and de-duplication). LLM agents and the deterministic secret",
        "scan are scored separately: the agent rows measure the models alone.",
        "",
        summary_table(results, info),
        "",
        "## Per case",
        "",
        "| Case | Expected | TP | FP | FN | Rule TP/FP | Tokens | Cost | Time | Errors |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for result in results:
        counts = sum(result.counts.values(), Counts())
        cost = "n/a" if result.cost_usd is None else f"${result.cost_usd:.4f}"
        expected = "clean" if result.clean else str(counts.tp + counts.fn)
        lines.append(
            f"| {result.name} | {expected} | {counts.tp} | {counts.fp} | {counts.fn} | "
            f"{result.rule_counts.tp}/{result.rule_counts.fp} | "
            f"{result.usage.total_tokens:,} | {cost} | {result.duration_seconds:.1f}s | "
            f"{'; '.join(result.errors) or ''} |"
        )
    return "\n".join(lines) + "\n"


def embed_in_readme(readme: str, table: str) -> str:
    """Replace the block between the README markers with `table`."""
    start, end = readme.find(README_START), readme.find(README_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README lacks the {README_START} / {README_END} markers")
    return readme[: start + len(README_START)] + "\n" + table + "\n" + readme[end:]
